def CompareDate_VEC(LDate, Opr, RDate):

    LEmpty = pd.isnull(LDate)
    REmpty = pd.isnull(RDate)
    Sel = ~(LEmpty & REmpty)

    LDate = LDate.fillna(DummyDate)
    RDate = RDate.fillna(DummyDate)



    if Opr == "==":
        ComResult = LDate == RDate
    elif Opr == "!=":
        ComResult = LDate != RDate
    elif Opr == ">":
        ComResult = LDate > RDate
    elif Opr == ">=":
        ComResult = LDate >= RDate
    elif Opr == "<":
        ComResult = LDate < RDate
    elif Opr == "<=":
        ComResult = LDate <= RDate
    ComResult = ComResult & Sel
    return ComResult



