def ValueToBoolean(aSeries, ValueToTrue):
    if not 'list' in str(type(ValueToTrue)):
        return aSeries == ValueToTrue
    else:
        SelOut = np.array([])
        SelTmp = np.array([])
        for aVal in ValueToTrue:
            SelTmp = aSeries == aVal
            if len(SelOut) == 0:
                SelOut = SelTmp
            else:
                SelOut = np.logical_or(SelOut, SelTmp)
        return SelOut


