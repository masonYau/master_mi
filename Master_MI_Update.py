def CompareDate(LDate, Opr, RDate):

    if pd.isnull(LDate) and pd.isnull(RDate):
        return False
    else:
        if pd.isnull(LDate):
            LDate = DummyDate
        if pd.isnull(RDate):
            RDate = DummyDate
        if RDate == DummyDate and LDate == DummyDate:
            return False
        if Opr == "==":
            return LDate == RDate
        elif Opr == "!=":
            return LDate != RDate
        elif Opr == ">":
            return LDate > RDate
        elif Opr == ">=":
            return LDate >= RDate
        elif Opr == "<":
            return LDate < RDate
        elif Opr == "<=":
            return LDate <= RDate





